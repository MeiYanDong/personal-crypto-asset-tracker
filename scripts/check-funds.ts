import assert from "node:assert/strict";
import { buildFunds, addressKey, units, type FundRegistry, type FundChain, type PersonalSnapshot } from "../shared/funds.js";
import { isWorkerRequest, workerToken } from "../server/funds.js";
const a = "0x" + "a".repeat(40), token = "0x" + "b".repeat(40), now = new Date().toISOString();
const registry: FundRegistry = { version: 1, generatedAt: now, addresses: [{ chainId: 1, address: a, project: "project", host: "server", role: "owner" }], tokens: [{ chainId: 1, address: token, symbol: "MM", decimals: 18, valuation: "reference" }], servers: [], gaps: [] };
const state = { wallets: [{ id: "one", address: a.toUpperCase().replace("0X", "0x"), label: "one" }], assetGroups: [], assignments: {} };
const personal: PersonalSnapshot = { generatedAt: now, walletSummary: [{ wallet: state.wallets[0], status: "ok", updatedAt: now, holdings: [{ walletAddress: a, chainIndex: "1", symbol: "ETH", tokenContractAddress: "", balance: 1, rawBalance: "1000000000000000000", tokenPrice: 2000, isRiskToken: false }] }] };
const chain: FundChain = { chainId: 1, startedAt: now, finishedAt: now, assets: [{ chainId: 1, address: null, symbol: "ETH", decimals: 18 }, registry.tokens[0]], rows: [{ address: a, balances: { native: "2000000000000000001", [token]: "9895402852313560389364328" } }], errors: [] };
let result = buildFunds(registry, [chain], personal, state);
assert.equal(result.view.totalUsd, 4000);
assert.equal(result.view.overlapCount, 1);
assert.equal(result.facts.filter(f => f.token === "native").length, 1);
assert.equal(result.facts.find(f => f.token === token)?.quantity, "9895402.852313560389364328");
assert.equal(result.view.unpricedCount, 1);
assert.equal(result.view.groups.asset.find(r => r.label === "MM")?.priced, 0);
assert.equal(result.view.groups.project.reduce((s, p) => s + p.usd, 0), result.view.totalUsd);
assert.equal(result.view.groups.host.reduce((s, p) => s + p.usd, 0), result.view.totalUsd);
assert.equal(result.view.conservativeUsd, 3200);
result = buildFunds(registry, [{ ...chain, rows: [{ address: a, balances: { native: null } }] }], personal, state);
assert.equal(result.view.totalUsd, 2000, "failed observation must not erase last successful personal holding");
result = buildFunds(registry, [], null, state);
assert.equal(result.view.unknownCount, 1);
assert.equal(result.addresses[0].priced, 0, "unknown must render unavailable, not a zero balance");
assert.notEqual(addressKey("SoLCase"), addressKey("solcase"));
assert.equal(units("123000000000000000000000001", 18), "123000000.000000000000000001");
assert.equal(units("10000000000000000000", 18), "10");
assert.equal(units("0", 18), "0");
assert.equal(isWorkerRequest("/funds/chain", "PUT", workerToken("owner"), "owner"), true);
for (const [path, method] of [["/state", "PUT"], ["/wallets", "DELETE"], ["/funds/worker-token", "GET"], ["/refresh", "POST"]]) assert.equal(isWorkerRequest(path, method, workerToken("owner"), "owner"), false);
assert.equal(isWorkerRequest("/funds/chain", "PUT", "", ""), false);
console.log("Funds checks passed: identity dedup, exact units, unknowns, grouping, estimates, restricted worker auth.");
